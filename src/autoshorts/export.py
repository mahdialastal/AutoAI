def _escape_subtitles_path(
    path: str,
) -> str:
    """
    Escape path for use inside
    FFmpeg subtitles filter.
    """
    safe = (
        path
        .replace(
            "\\",
            "\\\\",
        )
        .replace(
            ":",
            "\\:",
        )
        .replace(
            "'",
            "\\'",
        )
    )

    if not any(
        c in safe
        for c in " ,;[]"
    ):
        return safe

    return f"'{safe}'"


def write_srt(
    segments: list[dict],
    path: Path,
    start_offset: float = 0.0,
) -> None:
    """
    Write SRT from segments.

    Segment times are absolute.
    start_offset shifts display.
    """
    path = Path(path)

    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    lines = []

    for i, s in enumerate(
        segments,
        1,
    ):

        t0 = (
            s["start"]
            - start_offset
        )

        t1 = (
            s["end"]
            - start_offset
        )

        if t0 < 0:
            t0 = 0.0

        lines.append(
            f"{i}"
        )

        lines.append(
            f"{_ts(t0)} --> "
            f"{_ts(t1)}"
        )

        lines.append(
            s.get(
                "text",
                "",
            ).replace(
                "\n",
                " ",
            )
        )

        lines.append("")

    path.write_text(
        "\n".join(lines),
        encoding="utf-8",
    )


def _ts(
    sec: float,
) -> str:

    h = int(
        sec // 3600
    )

    m = int(
        (sec % 3600)
        // 60
    )

    s = (
        sec % 60
    )

    return (
        f"{h:02d}:"
        f"{m:02d}:"
        f"{int(s):02d},"
        f"{int(s % 1 * 1000):03d}"
    )
